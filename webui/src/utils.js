import { isKsuWebui } from 'kernelsu-alt';

export function isDev() {
    return import.meta.env.DEV && !isKsuWebui();
}

export function escapeHtml(str) {
    if (str === null || str === undefined) return '';
    return String(str)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}
